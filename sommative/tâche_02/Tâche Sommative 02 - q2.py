# Demander la température en Celsius
celsius = float(input("Entrez une température en degrée Celsius : "))

# Conversion
fahrenhit = (celsius * 9/5) + 32
kelvin = celsius + 273.15

# Affichage des résultats
print("Résultats :")
print("Température en fahrenhit :", fahrenhit)
print("Température en kelvin :", kelvin)